    /// <summary>
    /// 多语言本地化（8 种语言）。XAML 用 {Binding [key], Source={x:Static local:L10n.Instance}}，
    /// 代码用 L10n.T("key")。语言更改在下次启动生效（启动时从配置读取）。
    /// </summary>
    public sealed class L10n : INotifyPropertyChanged
    {
        public static L10n Instance { get; } = new();
        public static string CurrentLanguage { get; private set; } = "zh-CN";

        /// <summary>支持的 语言代码 → 该语言的原生名称（用于下拉选择）。</summary>
        public static (string Code, string NativeName)[] SupportedLanguages { get; } =
        {
            ("zh-CN", "中文"),
            ("en-US", "English"),
            ("ja-JP", "日本語"),
            ("ko-KR", "한국어"),
            ("fr-FR", "Français"),
            ("de-DE", "Deutsch"),
            ("es-ES", "Español"),
            ("ru-RU", "Русский"),
        };


        public string this[string key] =>
            Tables.TryGetValue(CurrentLanguage, out var t) && t.TryGetValue(key, out var v)
                ? v
                : (Tables["zh-CN"].TryGetValue(key, out var zh) ? zh : key);

        public void SetLanguage(string lang)
        {
            if (string.IsNullOrWhiteSpace(lang)) lang = "zh-CN";
            if (CurrentLanguage == lang) return;
            CurrentLanguage = lang;
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
        }

        public event PropertyChangedEventHandler? PropertyChanged;

        public static string T(string key) => Instance[key];

        private static Dictionary<string, Dictionary<string, string>>? _tables;
        private static Dictionary<string, Dictionary<string, string>> Tables =>
            _tables ??= BuildTables();

        private static Dictionary<string, Dictionary<string, string>> BuildTables()
        {
            var t = new Dictionary<string, Dictionary<string, string>>();
            var cur = CurrentLanguage;
            t[cur] = BuildTable(cur);
            if (cur != "zh-CN") t["zh-CN"] = BuildZh();
            return t;
        }

        private static Dictionary<string, string> BuildTable(string lang) => lang switch
        {
            "en-US" => BuildEn(),
            "ja-JP" => BuildJa(),
            "ko-KR" => BuildKo(),
            "fr-FR" => BuildFr(),
            "de-DE" => BuildDe(),
            "es-ES" => BuildEs(),
            "ru-RU" => BuildRu(),
            _ => BuildZh(),
        };


